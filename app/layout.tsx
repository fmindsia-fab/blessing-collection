import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  metadataBase: process.env.NEXT_PUBLIC_SITE_URL ? new URL(process.env.NEXT_PUBLIC_SITE_URL) : undefined,
  title: "Blessing Collection",
  description: "Catálogo digital para artesãs e lojistas apresentarem seus produtos.",
};

// Layout raiz sem identidade visual de loja: com múltiplas lojas simultâneas,
// não há uma única marca para pintar aqui. Cada árvore com tema próprio
// (loja pública por slug, painel administrativo) aplica o seu via
// buildStoreTheme + classe .brand-scope no próprio layout.
export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="pt-BR"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
